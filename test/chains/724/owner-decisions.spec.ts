import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";

test("owner-decisions-724.md has exactly 4 blanks if present", () => {
  const p = "owner-decisions-724.md";
  if (!existsSync(p)) return; // generated by verify-724; skip when absent
  const md = readFileSync(p, "utf8");
  const markers = (md.match(/\[OWNER DECISION \d+: ______\]/g) ?? []).length;
  assert.equal(markers, 4);
  assert.ok(!/\[OWNER DECISION \d+: (?!______)/.test(md));
});
